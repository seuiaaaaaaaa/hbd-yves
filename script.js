function createFloatingPieces() {
  floatingPieces.innerHTML = '';
  const kinds = ['heart', 'paper', 'star'];

  for (let i = 0; i < 22; i += 1) {
    const piece = document.createElement('span');
    const kind = kinds[i % kinds.length];

    piece.className = 'float-piece';
    piece.dataset.kind = kind;
    piece.style.left = `${Math.random() * 100}%`;
    piece.style.top = `${80 + Math.random() * 25}%`;
    piece.style.setProperty('--size', `${12 + Math.random() * 14}px`);
    piece.style.setProperty('--duration', `${9 + Math.random() * 8}s`);
    piece.style.animationDelay = `${Math.random() * 8}s`;
    floatingPieces.appendChild(piece);
  }
}

function openLetter(index, playAnimation) {
  state.currentLetterIndex = index;
  const letter = websiteData.letters[index];
  resetLetterTapState();

  state.openedLetters.add(letter.number);
  saveOpenedLetters();
  renderLetters();
  ensureAudioPlayers();

  if (letter.number === 19) {
    playFinalSong();
  } else {
    stopFinalSong();

    if (state.backgroundMusicEnabled) {
      playBackgroundSong();
    }
  }

  fillLetterContent(letter);
  setLetterFocusView(false);
  modalLetterBody.scrollTop = 0;
  letterModal.scrollTop = 0;

  letterModal.classList.remove('hidden');
  letterModal.setAttribute('aria-hidden', 'false');
  document.body.classList.add('modal-open');

  if (letter.number === 19) {
    letterModal.classList.add('final-letter');
    finalLetterPanel.classList.remove('hidden');
    window.setTimeout(() => burstConfetti(window.innerWidth / 2, window.innerHeight / 2.6, 100), 900);
  } else {
    letterModal.classList.remove('final-letter');
    finalLetterPanel.classList.add('hidden');
  }

  if (!playAnimation) {
    envelopeStage.classList.add('is-opening', 'show-paper');
    return;
  }

  envelopeStage.classList.remove('is-opening', 'show-paper');
  letterPaper.classList.remove('is-turning');
  void envelopeStage.offsetWidth;

  window.setTimeout(() => {
    envelopeStage.classList.add('is-opening');
  }, 40);

  window.setTimeout(() => {
    envelopeStage.classList.add('show-paper');
  }, 440);
}

function fillLetterContent(letter) {
  modalProgress.textContent = `Letter ${formatNumber(letter.number)} of ${websiteData.letters.length}`;
  modalLetterDate.textContent = letter.date;
  modalLetterNumber.textContent = `#${formatNumber(letter.number)}`;
  modalLetterTitle.textContent = letter.title;
  modalLetterBody.innerHTML = letter.body.map((paragraph) => `<p>${paragraph}</p>`).join('');

  prevLetterBtn.disabled = letter.number === 1;
  nextLetterBtn.disabled = letter.number === websiteData.letters.length;
  prevLetterBtn.style.opacity = prevLetterBtn.disabled ? '0.55' : '1';
  nextLetterBtn.style.opacity = nextLetterBtn.disabled ? '0.55' : '1';
}

function changeLetter(direction) {
  const nextIndex = state.currentLetterIndex + direction;

  if (nextIndex < 0 || nextIndex >= websiteData.letters.length) {
    return;
  }

  resetLetterTapState();
  letterPaper.classList.add('is-turning');

  window.setTimeout(() => {
    openLetter(nextIndex, false);
    letterPaper.classList.remove('is-turning');
  }, 240);
}

function closeLetterModal() {
  letterModal.classList.add('hidden');
  letterModal.setAttribute('aria-hidden', 'true');
  letterModal.classList.remove('final-letter');
  document.body.classList.remove('modal-open');
  resetLetterTapState();
  setLetterFocusView(false);
  stopFinalSong();

  if (state.backgroundMusicEnabled) {
    playBackgroundSong();
  }
}

function formatNumber(number) {
  return String(number).padStart(2, '0');
}

function ensureAudioPlayers() {
  if (state.backgroundAudio && state.finalAudio) {
    return;
  }

  const backgroundAudio = new Audio(websiteData.music.backgroundSrc);
  backgroundAudio.loop = true;
  backgroundAudio.preload = 'auto';
  backgroundAudio.volume = 0;
  backgroundAudio.addEventListener('error', () => {
    console.warn(
      `Could not load the background music file "${websiteData.music.backgroundSrc}".`
    );
  });

  const finalAudio = new Audio(websiteData.music.finalSrc);
  finalAudio.loop = true;
  finalAudio.preload = 'auto';
  finalAudio.volume = 0;
  finalAudio.addEventListener('error', () => {
    console.warn(`Could not load the final music file "${websiteData.music.finalSrc}".`);
  });

  state.backgroundAudio = backgroundAudio;
  state.finalAudio = finalAudio;
}

function playBackgroundSong() {
  if (!state.backgroundAudio) {
    return;
  }

  stopFinalSong();

  const playPromise = state.backgroundAudio.play();
  if (playPromise && typeof playPromise.catch === 'function') {
    playPromise.catch(() => {
      console.warn('Background music playback was blocked or could not start yet.');
    });
  }

  fadeAudioTo(state.backgroundAudio, websiteData.music.backgroundVolume, 700, 'backgroundFadeFrame');
}

function pauseBackgroundSong() {
  if (!state.backgroundAudio) {
    return;
  }

  fadeAudioTo(state.backgroundAudio, 0, 500, 'backgroundFadeFrame');
}

function playFinalSong() {
  if (!state.finalAudio) {
    return;
  }

  pauseBackgroundSong();
  state.finalAudio.currentTime = 0;

  const playPromise = state.finalAudio.play();
  if (playPromise && typeof playPromise.catch === 'function') {
    playPromise.catch(() => {
      console.warn('Final letter music playback was blocked or could not start yet.');
    });
  }

  fadeAudioTo(state.finalAudio, websiteData.music.finalVolume, 700, 'finalFadeFrame');
}

function stopFinalSong() {
  if (!state.finalAudio) {
    return;
  }

  fadeAudioTo(state.finalAudio, 0, 500, 'finalFadeFrame');
}

function updateAudioButton() {
  playAudioBtn.textContent = state.backgroundMusicEnabled ? 'Pause Audio' : 'Play Audio';
}

function toggleLetterFocusView() {
  if (letterModal.classList.contains('hidden')) {
    return;
  }

  const now = Date.now();
  if (now - state.lastFocusToggleTime < 420) {
    return;
  }

  state.lastFocusToggleTime = now;
  setLetterFocusView(!state.letterFocusView);
}

function handleLetterPaperDoubleClick(event) {
  event.preventDefault();

  if (Date.now() < state.suppressNextDoubleClickUntil) {
    return;
  }

  toggleLetterFocusView();
}

function setLetterFocusView(shouldFocus) {
  state.letterFocusView = shouldFocus;
  letterModal.classList.toggle('focus-letter-view', shouldFocus);
}

function handleLetterPaperTouch(event) {
  const now = Date.now();

  if (now - state.lastLetterTapTime < 320) {
    event.preventDefault();
    state.suppressNextDoubleClickUntil = now + 450;
    toggleLetterFocusView();
    state.lastLetterTapTime = 0;
    return;
  }

  state.lastLetterTapTime = now;
}

function resetLetterTapState() {
  state.lastLetterTapTime = 0;
  state.lastFocusToggleTime = 0;
  state.suppressNextDoubleClickUntil = 0;
}

function fadeAudioTo(audio, targetVolume, duration, frameKey) {
  if (!audio) {
    return;
  }

  if (state[frameKey]) {
    window.cancelAnimationFrame(state[frameKey]);
  }

  const startVolume = audio.volume;
  const startTime = performance.now();

  function step(now) {
    const progress = Math.min((now - startTime) / duration, 1);
    audio.volume = startVolume + (targetVolume - startVolume) * progress;

    if (progress < 1) {
      state[frameKey] = window.requestAnimationFrame(step);
      return;
    }

    audio.volume = targetVolume;

    if (targetVolume === 0) {
      audio.pause();
    }
  }

  state[frameKey] = window.requestAnimationFrame(step);
}

function burstConfetti(x, y, count) {
  const colors = ['#d995a3', '#f6c9d1', '#e8c09f', '#fff1bf', '#b6d2f1', '#ffffff'];

  for (let i = 0; i < count; i += 1) {
    const piece = document.createElement('span');
    const angle = Math.random() * Math.PI * 2;
    const distance = 60 + Math.random() * 180;
    const moveX = Math.cos(angle) * distance;
    const moveY = Math.sin(angle) * distance + 140;

    piece.className = 'confetti';
    piece.style.left = `${x}px`;
    piece.style.top = `${y}px`;
    piece.style.background = colors[i % colors.length];
    piece.style.setProperty('--move-x', `${moveX}px`);
    piece.style.setProperty('--move-y', `${moveY}px`);
    piece.style.setProperty('--spin', `${Math.random() * 720 - 360}deg`);
    confettiLayer.appendChild(piece);

    window.setTimeout(() => piece.remove(), 1800);
  }
}
