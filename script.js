window.addEventListener('keydown', (event) => {
  if (letterModal.classList.contains('hidden')) {
    return;
  }

  if (event.key === 'Escape') {
    closeLetterModal();
  }

  if (event.key === 'ArrowLeft') {
    changeLetter(-1);
  }

  if (event.key === 'ArrowRight') {
    changeLetter(1);
  }
});

function setupHeroBabyPhoto() {
  const polaroid = document.querySelector('.hero-polaroid');
  const photo = document.getElementById('heroBabyPhoto');

  if (!polaroid) {
    return;
  }

  if (!photo) {
    polaroid.classList.add('no-photo');
    return;
  }

  function markMissing() {
    polaroid.classList.add('no-photo');
    photo.remove();
  }

  photo.addEventListener('error', markMissing);

  if (photo.complete && photo.naturalWidth === 0) {
    markMissing();
  }
}

function createLetter(number, title, date, body) {
  return {
    number,
    title,
    date,
    body: body || [
      `[LETTER ${number} CONTENT HERE]`,
      `[Add another paragraph here for Letter ${number}.]`,
      `[Add the closing lines for Letter ${number} here.]`
    ]
  };
}

function loadOpenedLetters() {
  try {
    const saved = JSON.parse(window.localStorage.getItem(STORAGE_KEY) || '[]');
    return Array.isArray(saved) ? saved : [];
  } catch (error) {
    return [];
  }
}

function saveOpenedLetters() {
  window.localStorage.setItem(STORAGE_KEY, JSON.stringify([...state.openedLetters]));
}

function loadLettersPageState() {
  return window.localStorage.getItem(PAGE_STATE_KEY) === 'open';
}

function saveLettersPageState() {
  window.localStorage.setItem(PAGE_STATE_KEY, state.lettersPageOpen ? 'open' : 'closed');
}

function loadPanelState() {
  const saved = window.localStorage.getItem(PANEL_STATE_KEY);
  const validPanels = ['letters', 'memory', 'notes'];
  return validPanels.includes(saved) ? saved : 'letters';
}

function savePanelState() {
  window.localStorage.setItem(PANEL_STATE_KEY, state.activePanel);
}

function applyPageState() {
  document.body.classList.toggle('show-letters', state.lettersPageOpen);

  window.scrollTo({ top: 0, behavior: 'auto' });
}

function applyActivePanel() {
  const panels = {
    letters: lettersSection,
    memory: memorySection,
    notes: notesSection
  };

  Object.entries(panels).forEach(([panelName, panelElement]) => {
    panelElement.classList.toggle('is-active', state.activePanel === panelName);
  });

  sectionTabs.querySelectorAll('.section-tab-button').forEach((button) => {
    button.classList.toggle('is-active', button.dataset.panel === state.activePanel);
  });
}

function renderLetters() {
  lettersGrid.innerHTML = '';

  websiteData.letters.forEach((letter, index) => {
    const accentKind = accentKinds[index % accentKinds.length];
    const button = document.createElement('button');
    button.className = 'letter-envelope';
    button.type = 'button';
    button.dataset.index = index;
    button.dataset.accent = accentKind;
    button.setAttribute('aria-label', `Open letter ${letter.number}`);

    if (state.openedLetters.has(letter.number)) {
      button.classList.add('is-opened');
    }

    button.innerHTML = `
      <div class="letter-envelope-shell">
        <span class="washi washi-left"></span>
        <span class="washi washi-right"></span>
        <span class="spidey-accent spidey-accent-${accentKind}" aria-hidden="true"></span>
        <span class="envelope-number">${formatNumber(letter.number)}</span>
        <span class="opened-stamp">opened</span>
        <span class="seal"></span>
        <span class="envelope-status">${state.openedLetters.has(letter.number) ? 'read again' : 'sealed'}</span>
      </div>
    `;

    lettersGrid.appendChild(button);
  });
}

function renderMemories() {
  memoryBoard.innerHTML = '';

  websiteData.memories.forEach((memory, index) => {
    const accentKind = accentKinds[(index + 1) % accentKinds.length];
    const card = document.createElement('article');
    card.className = 'memory-polaroid';
    card.dataset.accent = accentKind;
    card.style.setProperty('--tilt', `${[-4, 3, -2, 2, -3, 4][index % 6]}deg`);

    const frameContent = memory.image
      ? `<img src="${encodeURI(memory.image)}" alt="${memory.title}">`
      : `<span>${memory.placeholder || 'A saved memory'}</span>`;

    card.innerHTML = `
      <span class="memory-accent memory-accent-${accentKind}" aria-hidden="true"></span>
      <div class="memory-frame">${frameContent}</div>
      <h3>${memory.title}</h3>
    `;

    memoryBoard.appendChild(card);
  });
}

